#!/usr/bin/env python3
"""Turns history.csv (the transcription of Exercise.pdf) into ../import_history.sql.

Run:  python3 build.py        (writes ../import_history.sql)
Nothing here ships to the browser.

Rules applied (all confirmed with the user):
  - PDF weights are lb; stored as kg, rounded to 3 decimals.
  - Each cell "sets reps weight" becomes `sets` rows, one per set.
  - plank, plank side and mabu are timed: every set is 30 seconds (the PDF's reps column held seconds
    in Dec 2025 and 10 afterwards, which the user said to treat as 30 s as well).
  - Weight 0 on an exercise without a weight metric becomes NULL.
  - walk farmer "3 50 50" is 3 sets of 50 m at 50 lb.
  - Two-sided exercises count both sides as one rep, so `side` stays NULL.
  - position numbers sets across the session in PDF row order.
"""
import csv, os
from collections import defaultdict

HERE = os.path.dirname(os.path.abspath(__file__))
OWNER_EMAIL = "lacche96@gmail.com"
LB_PER_KG = 2.20462
PLANK_SECONDS = 30

# name_en: (category, required, optional, primary, unilateral, parent)
LIFT = ("strength", "{reps,weight}", "{}", "weight")
CORE = ("core", "{reps}", "{weight}", "volume")
TIMED = ("{duration}", "{weight}", "duration")
CATALOG = {
    "squat dumbbell": (*LIFT, False, None),
    "lunge dumbbell": (*LIFT, False, None),
    "deadlift dumbbell": (*LIFT, False, None),
    "deadlift dumbbell stiff legged": (*LIFT, False, "deadlift dumbbell"),
    "curl hammer": (*LIFT, False, None),
    "curl dumbbell standing": (*LIFT, False, None),
    "curl zottman": (*LIFT, False, None),
    "extension dumbbell seated": (*LIFT, False, None),
    "extension dumbbell lying": (*LIFT, False, None),
    "row dumbbell bent over": (*LIFT, False, None),
    "row dumbbell one arm": (*LIFT, True, None),
    "fly dumbbell": (*LIFT, False, None),
    "fly dumbbell rear delt": (*LIFT, False, "fly dumbbell"),
    "lateral raises": (*LIFT, False, None),
    "press dumbbell": (*LIFT, False, None),
    "press dumbbell close grip": (*LIFT, False, "press dumbbell"),
    "press dumbbell reverse grip": (*LIFT, False, "press dumbbell"),
    "press dumbbell military": (*LIFT, False, "press dumbbell"),
    "crunches": (*CORE, False, None),
    "leg raise lying": (*CORE, False, None),
    "mountain climb rotating": (*CORE, False, None),
    "twist sitting": (*CORE, False, None),
    "plank": ("core", *TIMED, False, None),
    "plank side": ("core", *TIMED, True, "plank"),
    "mabu": ("strength", *TIMED, False, None),
    "walk farmer": ("strength", "{distance,weight}", "{duration}", "distance", False, None),
}
ZH = {"mabu": "马步"}  # the only Chinese name supplied
TIMED_NAMES = {"plank", "plank side", "mabu"}
NO_WEIGHT = {"crunches", "leg raise lying", "mountain climb rotating", "twist sitting"} | TIMED_NAMES

q = lambda s: "'" + s.replace("'", "''") + "'"
num = lambda v: "null" if v is None else (str(v).rstrip("0").rstrip(".") if "." in str(v) else str(v))

rows = list(csv.DictReader(open(os.path.join(HERE, "history.csv"), newline="")))
by_date = defaultdict(list)
for r in rows:
    by_date[r["date"]].append(r)

sets_out = []
for date in sorted(by_date):
    pos = 0
    for r in sorted(by_date[date], key=lambda r: int(r["row_order"])):
        name = r["exercise"]
        assert name in CATALOG, name
        n, x, w = int(r["sets"]), int(r["reps"]), int(r["weight_lb"])
        kg = round(w / LB_PER_KG, 3)
        for _ in range(n):
            pos += 1
            reps = weight = dur = dist = None
            if name in TIMED_NAMES:
                dur = PLANK_SECONDS
                weight = kg if w else None
            elif name == "walk farmer":
                dist, weight = x, kg
            else:
                reps = x
                weight = None if (name in NO_WEIGHT and w == 0) else kg
            sets_out.append((date, pos, name, reps, weight, dur, dist))

dates = sorted(by_date)
n_sets = len(sets_out)

L = []
A = L.append
A(f"""-- One-off import of Exercise.pdf into the exercise tables (generated by import/build.py; do not edit by hand).
-- Owner: {OWNER_EMAIL}.  {len(dates)} sessions, {n_sets} sets, {len(CATALOG)} exercises.
-- Run once in the Supabase SQL editor, after schema.sql, functions.sql and grants.sql.
-- It runs as one transaction: any failed check raises an error and nothing is written.
-- The editor has no signed-in user (auth.uid() is NULL), so user_id and created_by are written explicitly.
-- Exercises that already exist by name are reused. If the owner already has a session on any of
-- these dates the script stops before changing anything.

begin;

create temporary table imp_user (id uuid not null) on commit drop;
insert into imp_user select id from auth.users where email = {q(OWNER_EMAIL)};

do $$
begin
  if (select count(*) from imp_user) <> 1 then
    raise exception 'user {OWNER_EMAIL} not found in auth.users';
  end if;
  if not exists (select 1 from public.hub_profiles p join imp_user u on u.id = p.user_id) then
    raise exception 'no hub_profiles row for {OWNER_EMAIL}: run schema.sql first';
  end if;
  if exists (
    select 1 from public.exercise_sessions s join imp_user u on u.id = s.user_id
    where s.entry_date in ({", ".join(q(d) + "::date" for d in dates)})
  ) then
    raise exception 'sessions already exist on some of these dates; remove them first';
  end if;
end $$;

-- 1. Exercises (existing names are kept as they are)
insert into public.exercise_catalog
  (created_by, name_en, name_zh, category, required_metrics, optional_metrics, primary_metric, unilateral)
values""")
vals = []
for name, (cat, req, opt, prim, uni, parent) in CATALOG.items():
    zh = q(ZH[name]) if name in ZH else "null"
    vals.append(f"  ((select id from imp_user), {q(name)}, {zh}, {q(cat)}, {q(req)}, {q(opt)}, {q(prim)}, {'true' if uni else 'false'})")
A(",\n".join(vals))
A("on conflict (name_en) do nothing;\n")

A("-- 2. Families: variants point at their base exercise\nupdate public.exercise_catalog c set parent_id = p.id\nfrom (values")
A(",\n".join(f"  ({q(n)}, {q(v[5])})" for n, v in CATALOG.items() if v[5]))
A(") as f(child, parent)\njoin public.exercise_catalog p on p.name_en = f.parent\nwhere c.name_en = f.child and c.parent_id is null;\n")

A("-- 3. Sessions\ninsert into public.exercise_sessions (user_id, entry_date)\nselect (select id from imp_user), d::date from (values")
A(",\n".join(f"  ({q(d)})" for d in dates))
A(") as v(d);\n")

A("-- 4. Sets (weight in kg, converted from the PDF's lb; duration in seconds; distance in meters)\ninsert into public.exercise_sets\n  (user_id, session_id, exercise_id, position, reps, weight, duration_sec, distance_m)\nselect s.user_id, s.id, c.id, v.position, v.reps::int, v.weight::numeric, v.duration_sec::int, v.distance_m::numeric\nfrom (values")
A(",\n".join(f"  ({q(d)}, {p}, {q(n)}, {num(r)}, {num(w)}, {num(du)}, {num(di)})" for d, p, n, r, w, du, di in sets_out))
A(f""") as v(entry_date, position, name_en, reps, weight, duration_sec, distance_m)
join public.exercise_sessions s on s.user_id = (select id from imp_user) and s.entry_date = v.entry_date::date
join public.exercise_catalog c on c.name_en = v.name_en;

-- 5. Checks: any mismatch aborts the whole import
do $$
declare n_sessions int; n_sets int;
begin
  select count(*) into n_sessions from public.exercise_sessions s join imp_user u on u.id = s.user_id
    where s.entry_date in ({", ".join(q(d) + "::date" for d in dates)});
  select count(*) into n_sets from public.exercise_sets l
    join public.exercise_sessions s on s.id = l.session_id join imp_user u on u.id = s.user_id
    where s.entry_date in ({", ".join(q(d) + "::date" for d in dates)});
  if n_sessions <> {len(dates)} then raise exception 'expected {len(dates)} sessions, found %', n_sessions; end if;
  if n_sets <> {n_sets} then raise exception 'expected {n_sets} sets, found %', n_sets; end if;
end $$;

commit;

-- Spot checks (run afterwards, signed in or not; compare a few dates cell by cell with the PDF).
-- Expect {len(dates)} sessions and {n_sets} sets. The grid below shows sets, reps and weight in kg (PDF lb / 2.20462):
--   select coalesce(c.name_en, c.name_zh) as name, s.entry_date, count(*) as sets,
--          max(l.reps) as reps, max(l.weight) as weight_kg, max(l.duration_sec) as sec, max(l.distance_m) as meters
--   from public.exercise_sets l
--   join public.exercise_sessions s on s.id = l.session_id
--   join public.exercise_catalog c on c.id = l.exercise_id
--   where s.entry_date = '2026-04-03'
--   group by 1, 2 order by min(l.position);
""")
open(os.path.join(HERE, "..", "import_history.sql"), "w").write("\n".join(L))
print(len(dates), "sessions;", n_sets, "sets;", len(CATALOG), "exercises")
